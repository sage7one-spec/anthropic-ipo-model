// Regenerates snapshot.js (the offline fallback) from the captured fixtures in test/fixtures.
import { readFileSync, writeFileSync } from 'node:fs';
import { parseHyperliquid, parseBucketCurve, parseDateEvent, realizedVolFromCandles } from './model.js';
const fx = (n) => JSON.parse(readFileSync(`./test/fixtures/${n}`));
const hl = parseHyperliquid(fx('ant-hl-meta.json'), 'xyz:ANT');
const v = realizedVolFromCandles(fx('ant-hl-candles-1h.json'), 1);
// SPCX post-IPO path from the xyz:SPCX perp's daily closes, weekday sessions from the Jun 12 IPO,
// normalized to the Day-1 close ($166.72). NYSE holidays Jun 19, Jul 3, Sep 7 skipped.
const raw = [...fx('spcx-hl-candles-1d.json'), ...fx('spcx-hl-candles-1d-recent.json')];
const m = new Map(raw.map(k => [new Date(k.t).toISOString().slice(0, 10), +k.c]));
const hol = new Set(['2026-06-19', '2026-07-03', '2026-09-07']);
const days = [...m.keys()].filter(d => d >= '2026-06-12' && ![0, 6].includes(new Date(d + 'T12:00:00Z').getUTCDay()) && !hol.has(d)).sort();
const base = m.get('2026-06-12');
const snap = {
  asOf: '2026-10-31 16:20 UTC',
  hl,
  curve: parseBucketCurve(fx('ant-poly-close-cap.json')),
  valCurve: parseBucketCurve(fx('ant-poly-valuation.json')),
  raiseCurve: parseBucketCurve(fx('ant-poly-raise.json')),
  date: parseDateEvent(fx('ant-poly-date.json')),
  vol: { hourlySigma: v.hourlySigma, sessionSigma: v.sessionSigma },
  spcx: { ipoIso: '2026-06-12', offer: 135, day1Close: base, lastIso: days[days.length - 1],
          path: days.map(d => +(m.get(d) / base).toFixed(4)) },
};
writeFileSync('snapshot.js', '// Generated by scripts_gen_snapshot.mjs from test/fixtures (captured 2026-10-31). Offline fallback only.\nexport const BAKED_SNAPSHOT = ' + JSON.stringify(snap, null, 1) + ';\n');
console.log('hl', hl.mark, 'curve', snap.curve.length, 'val', snap.valCurve.length, 'raise', snap.raiseCurve.length, 'dates', snap.date.dates.length, 'spcx', snap.spcx.path.length, 'sess', v.sessionSigma.toFixed(4));
